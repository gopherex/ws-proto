//! Emits, per service, a `pub mod <service>_ws` holding:
//!
//! - `SERVICE_NAME` and one `MethodSpec` const per method;
//! - `<Service>Handler`: the server trait (one method per RPC, shaped like the
//!   Go `<Service>Handler` interface) plus `register_<service>`;
//! - `<Method>ServerStream`: typed server-side stream wrappers;
//! - `<Service>Client` with typed `<Method>ClientStream` wrappers.
//!
//! tonic services need no generated glue: `ws_proto::Server::register_grpc`
//! serves them directly.
//!
//! The module is `include!`d next to the prost message types, so those are
//! reached as `super::Type` (see [`Resolver`]).

use heck::{ToShoutySnakeCase, ToUpperCamelCase};
use proc_macro2::{Ident, TokenStream};
use prost_build::Module;
use prost_types::{
    compiler::code_generator_response::File, FileDescriptorProto, MethodDescriptorProto,
    ServiceDescriptorProto,
};
use protoc_gen_prost::{Generator, ModuleRequest, ModuleRequestSet, Result};
use quote::{format_ident, quote};

use crate::{resolver::Resolver, util};

pub(crate) struct WsGenerator {
    pub(crate) resolver: Resolver,
    pub(crate) generate_server: bool,
    pub(crate) generate_client: bool,
    pub(crate) insert_include: bool,
}

impl Generator for WsGenerator {
    fn generate(&mut self, module_request_set: &ModuleRequestSet) -> Result {
        module_request_set
            .requests()
            .filter_map(|(module, request)| self.handle_module_request(module, request))
            .flatten()
            .map(Ok)
            .collect()
    }
}

/// One RPC, resolved: identifiers and Rust type paths.
struct Method {
    /// `UpperCamel` proto name, e.g. `ServerStream`.
    proto_name: String,
    /// `/pkg.Service/Method`.
    path: String,
    /// `snake_case` fn name.
    fn_name: Ident,
    /// `SHOUTY_SNAKE` const name.
    const_name: Ident,
    req: TokenStream,
    resp: TokenStream,
    client_streaming: bool,
    server_streaming: bool,
    doc: String,
}

impl Method {
    fn server_wrapper(&self) -> Ident {
        format_ident!("{}ServerStream", self.proto_name.to_upper_camel_case())
    }
    fn client_wrapper(&self) -> Ident {
        format_ident!("{}ClientStream", self.proto_name.to_upper_camel_case())
    }
    fn is_unary(&self) -> bool {
        !self.client_streaming && !self.server_streaming
    }
}

impl WsGenerator {
    fn handle_module_request(&self, module: &Module, request: &ModuleRequest) -> Option<Vec<File>> {
        let output_filename = format!("{}.ws.rs", request.proto_package_name());

        let services: TokenStream = request
            .files()
            .flat_map(|file| {
                file.service
                    .iter()
                    .enumerate()
                    .map(move |(i, svc)| self.generate_service(module, file, svc, i))
            })
            .collect();

        if services.is_empty() {
            return None;
        }

        let mut res = Vec::with_capacity(2);
        if self.insert_include {
            res.push(request.append_to_file(|buf| {
                buf.push_str("include!(\"");
                buf.push_str(&output_filename);
                buf.push_str("\");\n");
            })?);
        }

        let file = syn::parse2(services).expect("generated code is a valid rust file");
        res.push(File {
            name: Some(request.output_dir() + &output_filename),
            content: Some(format!(
                "// @generated by protoc-gen-ws-rs. DO NOT EDIT.\n{}",
                prettyplease::unparse(&file)
            )),
            ..File::default()
        });
        Some(res)
    }

    fn generate_service(
        &self,
        module: &Module,
        file: &FileDescriptorProto,
        svc: &ServiceDescriptorProto,
        service_index: usize,
    ) -> TokenStream {
        let service_fq = format!("{}.{}", file.package(), svc.name());
        let mod_name = format_ident!("{}_ws", util::to_snake(svc.name()));
        let svc_camel = svc.name().to_upper_camel_case();

        let methods: Vec<Method> = svc
            .method
            .iter()
            .enumerate()
            .map(|(i, m)| self.method(module, &service_fq, file, service_index, i, m))
            .collect();

        let service_doc = util::leading_comment(file, &[6, service_index as i32]);
        let mod_doc = format!(
            " ws-proto bindings for the `{service_fq}` service.{}",
            if service_doc.is_empty() {
                String::new()
            } else {
                format!("\n\n{}", service_doc.trim_end())
            }
        );

        let infos = methods.iter().map(|m| {
            let Method {
                const_name, path, ..
            } = m;
            let kind = match (m.client_streaming, m.server_streaming) {
                (false, false) => quote!(StreamKind::Unary),
                (false, true) => quote!(StreamKind::ServerStream),
                (true, false) => quote!(StreamKind::ClientStream),
                (true, true) => quote!(StreamKind::BidiStream),
            };
            quote! {
                pub const #const_name: MethodSpec = MethodSpec { route: #path, kind: #kind };
            }
        });

        let server = self
            .generate_server
            .then(|| self.gen_server(&svc_camel, &methods));
        let client = self
            .generate_client
            .then(|| self.gen_client(&svc_camel, &methods));

        quote! {
            #[doc = #mod_doc]
            #[allow(dead_code, unused_imports, clippy::module_inception)]
            pub mod #mod_name {
                use ::ws_proto::{
                    client::{recv_msg, send_msg}, CallOptions, Client as WsClient, Metadata,
                    MethodSpec, Request, Response, Server, Status, Stream, StreamKind,
                    StreamingConn,
                };

                /// Fully-qualified protobuf service name.
                pub const SERVICE_NAME: &str = #service_fq;

                #(#infos)*

                #server
                #client
            }
        }
    }

    #[allow(clippy::too_many_arguments)]
    fn method(
        &self,
        module: &Module,
        service_fq: &str,
        file: &FileDescriptorProto,
        service_index: usize,
        method_index: usize,
        m: &MethodDescriptorProto,
    ) -> Method {
        let parse = |s: String| -> TokenStream { s.parse().expect("type path") };
        Method {
            proto_name: m.name().to_owned(),
            path: format!("/{service_fq}/{}", m.name()),
            fn_name: format_ident!("{}", util::to_snake(m.name())),
            const_name: format_ident!("{}", m.name().to_shouty_snake_case()),
            req: parse(self.resolver.resolve_ident(module, m.input_type())),
            resp: parse(self.resolver.resolve_ident(module, m.output_type())),
            client_streaming: m.client_streaming(),
            server_streaming: m.server_streaming(),
            doc: util::leading_comment(file, &[6, service_index as i32, 2, method_index as i32]),
        }
    }

    // ---------------------------------------------------------------- server

    fn gen_server(&self, svc: &str, methods: &[Method]) -> TokenStream {
        let trait_name = format_ident!("{svc}Handler");
        let register = format_ident!("register_{}", util::to_snake(svc));
        let register_arc = format_ident!("register_{}_arc", util::to_snake(svc));

        let trait_methods = methods.iter().map(|m| {
            let Method { fn_name, req, resp, doc, .. } = m;
            let wrapper = m.server_wrapper();
            let doc = doc_attr(doc);
            match (m.client_streaming, m.server_streaming) {
                (false, false) => quote! {
                    #doc
                    fn #fn_name(&self, req: Request<#req>)
                        -> impl ::core::future::Future<Output = Result<Response<#resp>, Status>> + Send;
                },
                (false, true) => quote! {
                    #doc
                    fn #fn_name(&self, req: Request<#req>, stream: #wrapper)
                        -> impl ::core::future::Future<Output = Result<(), Status>> + Send;
                },
                (true, false) => quote! {
                    #doc
                    fn #fn_name(&self, stream: #wrapper)
                        -> impl ::core::future::Future<Output = Result<Response<#resp>, Status>> + Send;
                },
                (true, true) => quote! {
                    #doc
                    fn #fn_name(&self, stream: #wrapper)
                        -> impl ::core::future::Future<Output = Result<(), Status>> + Send;
                },
            }
        });

        let wrappers = methods.iter().filter(|m| !m.is_unary()).map(|m| {
            let Method {
                req,
                resp,
                proto_name,
                ..
            } = m;
            let name = m.server_wrapper();
            let doc = format!(" Typed server-side stream for `{svc}.{proto_name}`.");
            quote! {
                #[doc = #doc]
                #[derive(Clone, Debug)]
                pub struct #name {
                    inner: Stream,
                }

                impl #name {
                    /// Request headers from the OPEN frame.
                    pub fn header(&self) -> Metadata { self.inner.header() }
                    /// Caller deadline budget (`ws-timeout-ms`), if any.
                    pub fn timeout(&self) -> Option<::core::time::Duration> { self.inner.timeout() }
                    /// Sends one leading HEADER frame; must precede the first `send`.
                    pub async fn send_header(&self, md: Metadata) -> Result<(), Status> {
                        self.inner.send_header(md).await
                    }
                    /// Merges trailers flushed with the END frame.
                    pub fn set_trailer(&self, md: Metadata) { self.inner.set_trailer(md) }
                    /// Sends one response message (awaits flow-control credit).
                    pub async fn send(&self, msg: &#resp) -> Result<(), Status> {
                        self.inner.send(msg).await
                    }
                    /// Receives the next request; `Ok(None)` once the client half-closes.
                    pub async fn recv(&self) -> Result<Option<#req>, Status> {
                        self.inner.recv().await
                    }
                    /// The underlying untyped stream.
                    pub fn raw(&self) -> &Stream { &self.inner }
                }
            }
        });

        let registrations = methods.iter().map(|m| {
            let Method {
                fn_name,
                const_name,
                req,
                ..
            } = m;
            let wrapper = m.server_wrapper();
            match (m.client_streaming, m.server_streaming) {
                (false, false) => quote! {
                    {
                        let h = ::std::sync::Arc::clone(&handler);
                        server.register_unary(#const_name.route, move |req: Request<#req>| {
                            let h = ::std::sync::Arc::clone(&h);
                            async move { h.#fn_name(req).await }
                        });
                    }
                },
                (false, true) => quote! {
                    {
                        let h = ::std::sync::Arc::clone(&handler);
                        server.register(#const_name.route, move |s: Stream| {
                            let h = ::std::sync::Arc::clone(&h);
                            async move {
                                // Tolerate a half-close with no message, as Go does (io.EOF).
                                let msg = s.recv::<#req>().await?.unwrap_or_default();
                                let req = Request { msg, header: s.header(), timeout: s.timeout() };
                                h.#fn_name(req, #wrapper { inner: s }).await
                            }
                        });
                    }
                },
                (true, false) => quote! {
                    {
                        let h = ::std::sync::Arc::clone(&handler);
                        server.register(#const_name.route, move |s: Stream| {
                            let h = ::std::sync::Arc::clone(&h);
                            async move {
                                let resp = h.#fn_name(#wrapper { inner: s.clone() }).await?;
                                if !resp.header.is_empty() {
                                    let _ = s.send_header(resp.header).await;
                                }
                                s.set_trailer(resp.trailer);
                                s.send(&resp.msg).await
                            }
                        });
                    }
                },
                (true, true) => quote! {
                    {
                        let h = ::std::sync::Arc::clone(&handler);
                        server.register(#const_name.route, move |s: Stream| {
                            let h = ::std::sync::Arc::clone(&h);
                            async move { h.#fn_name(#wrapper { inner: s }).await }
                        });
                    }
                },
            }
        });

        let trait_doc = format!(" Server API for the `{svc}` service. Implement with `async fn`.");
        let register_doc = format!(" Registers `handler` on `server` for every `{svc}` method.");
        quote! {
            #[doc = #trait_doc]
            pub trait #trait_name: Send + Sync + 'static {
                #(#trait_methods)*
            }

            #(#wrappers)*

            #[doc = #register_doc]
            pub fn #register<H: #trait_name>(server: &Server, handler: H) {
                #register_arc(server, ::std::sync::Arc::new(handler))
            }

            #[doc = #register_doc]
            pub fn #register_arc<H: #trait_name>(server: &Server, handler: ::std::sync::Arc<H>) {
                #(#registrations)*
            }
        }
    }

    // ---------------------------------------------------------------- client

    fn gen_client(&self, svc: &str, methods: &[Method]) -> TokenStream {
        let client_name = format_ident!("{svc}Client");

        let calls = methods.iter().map(|m| {
            let Method { fn_name, const_name, req, resp, doc, .. } = m;
            let wrapper = m.client_wrapper();
            let doc = doc_attr(doc);
            match (m.client_streaming, m.server_streaming) {
                (false, false) => quote! {
                    #doc
                    pub async fn #fn_name(&self, req: impl Into<Request<#req>>)
                        -> Result<Response<#resp>, Status>
                    {
                        self.conn.invoke_unary(#const_name, req.into()).await
                    }
                },
                (false, true) => quote! {
                    #doc
                    pub async fn #fn_name(&self, req: impl Into<Request<#req>>)
                        -> Result<#wrapper, Status>
                    {
                        let req = req.into();
                        let conn = self.conn.open_streaming(#const_name, req.header, req.timeout).await?;
                        send_msg(&conn, &req.msg).await?;
                        conn.close_request().await?;
                        Ok(#wrapper { inner: conn })
                    }
                },
                _ => quote! {
                    #doc
                    pub async fn #fn_name(&self, opts: CallOptions) -> Result<#wrapper, Status> {
                        let conn = self.conn.open_streaming(#const_name, opts.header, opts.timeout).await?;
                        Ok(#wrapper { inner: conn })
                    }
                },
            }
        });

        let wrappers = methods.iter().filter(|m| !m.is_unary()).map(|m| {
            let Method {
                req,
                resp,
                proto_name,
                ..
            } = m;
            let name = m.client_wrapper();
            let doc = format!(" Typed client-side stream for `{svc}.{proto_name}`.");
            let send = m.client_streaming.then(|| {
                quote! {
                    /// Sends one request message (awaits flow-control credit).
                    pub async fn send(&self, msg: &#req) -> Result<(), Status> {
                        send_msg(&self.inner, msg).await
                    }
                    /// Signals that no more requests follow (HALF_CLOSE).
                    pub async fn close_send(&self) -> Result<(), Status> {
                        self.inner.close_request().await
                    }
                }
            });
            let recv = if m.server_streaming {
                quote! {
                    /// Receives the next response; `Ok(None)` on a clean END, `Err` on a
                    /// non-OK status.
                    pub async fn recv(&self) -> Result<Option<#resp>, Status> {
                        recv_msg(&self.inner).await
                    }
                }
            } else {
                quote! {
                    /// Half-closes, receives the single response and drains the END so a
                    /// trailing error status is surfaced.
                    pub async fn close_and_recv(&self) -> Result<Response<#resp>, Status> {
                        self.inner.close_request().await?;
                        let msg = match recv_msg::<#resp>(&self.inner).await? {
                            Some(m) => m,
                            None => return Err(Status::new(
                                ::ws_proto::Code::Internal,
                                "wsrpc: call ended without a response message",
                            )),
                        };
                        if self.inner.receive().await?.is_some() {
                            return Err(Status::new(
                                ::ws_proto::Code::Internal,
                                "wsrpc: received more than one response message",
                            ));
                        }
                        Ok(Response {
                            msg,
                            header: self.inner.response_header(),
                            trailer: self.inner.response_trailer(),
                        })
                    }
                }
            };
            quote! {
                #[doc = #doc]
                #[derive(Clone)]
                pub struct #name {
                    inner: StreamingConn,
                }

                impl #name {
                    #send
                    #recv
                    /// Leading response metadata (HEADER frame), if the server sent one.
                    pub fn header(&self) -> Metadata { self.inner.response_header() }
                    /// Trailers from the END frame; empty until the stream has ended.
                    pub fn trailer(&self) -> Metadata { self.inner.response_trailer() }
                    /// The underlying (interceptor-wrapped) streaming connection.
                    pub fn raw(&self) -> &StreamingConn { &self.inner }
                }
            }
        });

        let doc = format!(" Typed client for the `{svc}` service over a `ws_proto::Client`.");
        quote! {
            #[doc = #doc]
            #[derive(Clone, Debug)]
            pub struct #client_name {
                conn: WsClient,
            }

            impl #client_name {
                pub fn new(conn: WsClient) -> Self { Self { conn } }
                /// The underlying connection.
                pub fn conn(&self) -> &WsClient { &self.conn }
                #(#calls)*
            }

            #(#wrappers)*
        }
    }
}

fn doc_attr(doc: &str) -> TokenStream {
    if doc.trim().is_empty() {
        return TokenStream::new();
    }
    let lines = doc.lines().map(|l| format!(" {}", l.trim_end()));
    quote! { #(#[doc = #lines])* }
}
