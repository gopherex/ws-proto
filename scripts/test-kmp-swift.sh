#!/usr/bin/env bash
# Build a genuine KMP+SKIE framework, then execute Swift tests on an owned iOS simulator.
set -euo pipefail

if [[ $(uname -s) != Darwin ]]; then
  echo "KMP Swift integration requires macOS with Xcode and an iOS simulator runtime" >&2
  exit 2
fi
: "${WS_PROTO_TEST_URL:?Run scripts/with-mobile-server.sh scripts/test-kmp-swift.sh}"

root=$(cd "$(dirname "$0")/.." && pwd)
if [[ -z ${WS_PROTO_IOS_DEVICE:-} ]]; then
  exec "$root/scripts/with-ios-simulator.sh" "$0" "$@"
fi
fixture="$root/tests/kmp-consumer"
gradle_args=(-p "$fixture" --no-daemon)
if [[ -n ${WS_PROTO_VERSION:-} ]]; then
  : "${GITHUB_ACTOR:?Published package testing requires GITHUB_ACTOR}"
  : "${GITHUB_TOKEN:?Published package testing requires GITHUB_TOKEN with read:packages}"
  gradle_args+=("-PwsProtoVersion=$WS_PROTO_VERSION")
fi

case $(uname -m) in
  arm64) target=iosSimulatorArm64; link_task=linkDebugFrameworkIosSimulatorArm64 ;;
  x86_64) target=iosX64; link_task=linkDebugFrameworkIosX64 ;;
  *) echo "Unsupported simulator host architecture: $(uname -m)" >&2; exit 2 ;;
esac

"$root/packages/ws-proto-kotlin/gradlew" "${gradle_args[@]}" linkDebugFrameworkIosArm64 "$link_task"
framework="$fixture/build/bin/$target/debugFramework/KmpFixture.framework"
device_framework="$fixture/build/bin/iosArm64/debugFramework/KmpFixture.framework"
test -d "$framework"
test -d "$device_framework"
# This is a generated framework owned by this fixture, never a source artifact.
rm -rf "$fixture/swift/KmpFixture.xcframework"
xcodebuild -create-xcframework -framework "$framework" -framework "$device_framework" -output "$fixture/swift/KmpFixture.xcframework"

python3 - "$fixture/swift/Tests/KmpConsumerTests/Endpoint.generated.swift" <<'PY'
import json, os, pathlib, sys, urllib.parse
endpoint = os.environ["WS_PROTO_TEST_URL"]
url = urllib.parse.urlparse(endpoint)
if url.scheme != "ws" or url.hostname not in ("127.0.0.1", "localhost"):
    raise SystemExit("The simulator fixture requires a local ws:// endpoint")
pathlib.Path(sys.argv[1]).write_text("// Generated by test-kmp-swift.sh.\nlet fixtureEndpoint = " + json.dumps(endpoint) + "\n")
PY

cleanup() {
  rm -f "$fixture/swift/Tests/KmpConsumerTests/Endpoint.generated.swift"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

cd "$fixture/swift"
xcodebuild -scheme KmpConsumer \
  -destination "platform=iOS Simulator,id=$WS_PROTO_IOS_DEVICE" \
  -derivedDataPath "$fixture/build/DerivedData" \
  -resultBundlePath "$fixture/build/SwiftTests-$(date +%s).xcresult" \
  -parallel-testing-enabled NO \
  CODE_SIGNING_ALLOWED=NO test
