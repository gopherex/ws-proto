package mobilegen

import (
	"fmt"
	"strings"

	"google.golang.org/protobuf/reflect/protoreflect"
)

func generateSwift(file protoreflect.FileDescriptor, options settings) (string, error) {
	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by protoc-gen-ws-swift. DO NOT EDIT.\n// source: %s\n\n", file.Path())
	imports := map[string]bool{"SwiftProtobuf": true, "WsProto": true, "_Concurrency": true}
	for i := 0; i < file.Services().Len(); i++ {
		service := file.Services().Get(i)
		if prefix := swiftPrefix(file); prefix != "" && !validIdentifier(prefix) {
			return "", fmt.Errorf("%s: invalid swift_prefix %q", file.Path(), prefix)
		}
		for j := 0; j < service.Methods().Len(); j++ {
			method := service.Methods().Get(j)
			for _, message := range []protoreflect.MessageDescriptor{method.Input(), method.Output()} {
				if prefix := swiftPrefix(message.ParentFile()); prefix != "" && !validIdentifier(prefix) {
					return "", fmt.Errorf("%s: invalid swift_prefix %q", message.ParentFile().Path(), prefix)
				}
				module := swiftModule(message.ParentFile().Path(), options)
				if module != "" && module != swiftModule(file.Path(), options) {
					imports[module] = true
				}
			}
		}
	}
	for _, name := range sortedKeys(imports) {
		fmt.Fprintf(&out, "import %s\n", name)
	}
	for i := 0; i < file.Services().Len(); i++ {
		service := file.Services().Get(i)
		fmt.Fprintf(&out, "\n%s final class %sClient: Swift.Sendable {\n    private let transport: WsProto.WsTransport\n\n    %s init(transport: WsProto.WsTransport) {\n        self.transport = transport\n    }\n", options.visibility, swiftPrefix(file)+string(service.Name()), options.visibility)
		for j := 0; j < service.Methods().Len(); j++ {
			swiftMethod(&out, service.Methods().Get(j), file, options)
		}
		out.WriteString("}\n")
	}
	return out.String(), nil
}

func swiftMethod(out *strings.Builder, method protoreflect.MethodDescriptor, file protoreflect.FileDescriptor, options settings) {
	input, output := swiftName(method.Input(), file, options), swiftName(method.Output(), file, options)
	name := methodName(string(method.Name()))
	service := method.Parent().FullName()
	route := "/" + string(service) + "/" + string(method.Name())
	result, operation := "WsProto.UnaryResponse<"+output+">", "unary"
	if method.IsStreamingServer() {
		result = "WsProto.ResponseStream<" + output + ">"
		operation = "serverStreaming"
	}
	if method.IsStreamingClient() {
		operation = "clientStreaming"
		if method.IsStreamingServer() {
			operation = "bidiStreaming"
		}
		generic := "WSRequests"
		for generic == input || generic == output {
			generic += "_"
		}
		fmt.Fprintf(out, "\n    %s func `%s`<%s: _Concurrency.AsyncSequence & Swift.Sendable>(_ requests: %s, options: WsProto.CallOptions = .init()) async throws -> %s where %s.Element == %s {\n", options.visibility, name, generic, generic, result, generic, input)
		fmt.Fprintf(out, "        try await transport.%s(method: %q, requests: requests, responseType: %s.self, options: options)\n", operation, route, output)
	} else {
		fmt.Fprintf(out, "\n    %s func `%s`(_ request: %s, options: WsProto.CallOptions = .init()) async throws -> %s {\n", options.visibility, name, input, result)
		fmt.Fprintf(out, "        try await transport.%s(method: %q, request: request, responseType: %s.self, options: options)\n", operation, route, output)
	}
	out.WriteString("    }\n")
}
