package mobilegen

import (
	"fmt"
	"strings"

	"google.golang.org/protobuf/reflect/protoreflect"
)

func generateKotlin(service protoreflect.ServiceDescriptor) string {
	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by protoc-gen-ws-kotlin. DO NOT EDIT.\n// source: %s\n\n", service.ParentFile().Path())
	if pkg := javaPackage(service.ParentFile()); pkg != "" {
		fmt.Fprintf(&out, "package %s\n\n", kotlinQualified(pkg))
	}
	out.WriteString("import kotlinx.coroutines.flow.Flow\nimport kotlinx.coroutines.flow.flow\nimport kotlinx.coroutines.flow.flowOf\nimport kotlinx.coroutines.flow.emitAll\n\n")
	fmt.Fprintf(&out, "public class `%sClient`(private val transport: io.gopherex.wsproto.WsTransport) {\n", service.Name())
	for i := 0; i < service.Methods().Len(); i++ {
		method := service.Methods().Get(i)
		input, output := kotlinName(method.Input()), kotlinName(method.Output())
		name := methodName(string(method.Name()))
		fmt.Fprintf(&out, "\n    private val wsMethod%d = io.gopherex.wsproto.MethodInfo<%s, %s>(\n        typeName = %q, name = %q,\n        kind = io.gopherex.wsproto.MethodKind.%s, output = %s.parser(),\n    )\n", i, input, output, service.FullName(), method.Name(), methodKind(method), output)
		requestType, requestName, requestExpr := input, "request", "flowOf(request)"
		if method.IsStreamingClient() {
			requestType = "Flow<" + input + ">"
			requestName = "requests"
			requestExpr = "requests"
		}
		if method.IsStreamingServer() {
			fmt.Fprintf(&out, "\n    public fun `%s`(%s: %s, options: io.gopherex.wsproto.CallOptions = io.gopherex.wsproto.CallOptions()): Flow<%s> = flow {\n        emitAll(transport.stream(wsMethod%d, %s, options).message)\n    }\n", name, requestName, requestType, output, i, requestExpr)
		} else {
			fmt.Fprintf(&out, "\n    public suspend fun `%s`(%s: %s, options: io.gopherex.wsproto.CallOptions = io.gopherex.wsproto.CallOptions()): %s =\n", name, requestName, requestType, output)
			if method.IsStreamingClient() {
				fmt.Fprintf(&out, "        io.gopherex.wsproto.firstResponse(transport.stream(wsMethod%d, requests, options))\n", i)
			} else {
				fmt.Fprintf(&out, "        transport.unary(wsMethod%d, request, options).message\n", i)
			}
		}
	}
	out.WriteString("}\n")
	return out.String()
}

func methodKind(method protoreflect.MethodDescriptor) string {
	if method.IsStreamingClient() && method.IsStreamingServer() {
		return "BIDI_STREAMING"
	}
	if method.IsStreamingClient() {
		return "CLIENT_STREAMING"
	}
	if method.IsStreamingServer() {
		return "SERVER_STREAMING"
	}
	return "UNARY"
}
